import { describe, expect, it } from 'vitest';
import { challengeS256, randomString } from './pkce';

describe('pkce', () => {
  it('matches the RFC 7636 appendix B test vector', async () => {
    expect(await challengeS256('dBjftJeZ4CVP-mB92K27uhbUJU1p1r_wW1gFWFOEjXk')).toBe('E9Melhoa2OwvFrEMTJguCHaoeK1t8URWbuGJSstw-cM');
  });
  it('generates URL-safe, unique values', () => {
    const a = randomString();
    expect(a).toMatch(/^[A-Za-z0-9_-]{43}$/);
    expect(randomString()).not.toBe(a);
  });
});
